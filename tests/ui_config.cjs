const assert = require('node:assert/strict');
const fs = require('node:fs');
const model = new Function('baseclass',fs.readFileSync('packages/luci-app-campuslink/htdocs/luci-static/resources/campuslink/config.js','utf8'))({extend:x=>x});
const provider = JSON.parse(fs.readFileSync('packages/campuslink/files/usr/share/campuslink/providers/drcom-http.json'));
const school = JSON.parse(fs.readFileSync('packages/campuslink/files/usr/share/campuslink/schools/local-campus.json'));
const data = {providers:[provider],schools:[school],interfaces:[{interface:'lan'},{interface:'wan1'},{interface:'wan2'},{interface:'wan3'}]};
const account = {id:'a1',label:'Account A',credential_type:'username_password',values:{username:'fake-user'},password_set:true};
const line = {id:'c1',label:'WAN 1',interface:'wan1',provider:'drcom-http',school:'local-campus',account:'a1',params:{terminal_mode:'pc'},enabled:true,auto_login:true,check_interval:60,retry_interval:30,retry_max:600};
const config = {schema_version:1,generation:7,accounts:[account],connections:[line,{...model.copy(line),id:'c2',interface:'wan2'}]};
const original = JSON.stringify(config);

let draft = model.lineDraft(line,data);
draft.params.auth_server = '2.2.2.2';
let next = model.saveLine(config,draft,null);
assert.equal(next.generation,7);
assert.deepEqual(next.accounts,config.accounts);
assert.deepEqual(next.connections[1],config.connections[1]);
assert.equal(JSON.stringify(config),original,'editing/cancel must not mutate loaded config');
assert.deepEqual(model.endpoints('2.2.2.2'),{auth_url:'http://2.2.2.2:801/eportal/portal/login',status_url:'http://2.2.2.2/',logout_url:'http://2.2.2.2:801/eportal/portal/logout'});
const oldSchool = {...school,defaults:{...model.endpoints('old.example'),terminal_mode:'pc'}};
const oldData = {...data,schools:[oldSchool]};
draft = model.lineDraft(line,oldData);
assert.equal(model.params(draft,oldData).auth_server,'old.example');
draft.params.auth_server='new.example';
assert.equal(model.params(draft,oldData).auth_url,undefined,'canonical school URL must become derived');
assert.equal(model.endpoints(model.params(draft,oldData).auth_server).auth_url,'http://new.example:801/eportal/portal/login');
assert.equal(oldSchool.defaults.auth_url,'http://old.example:801/eportal/portal/login','normalize without changing installed preset');

const legacy = model.copy(line);
legacy.params = {...model.endpoints('2.2.2.2'),terminal_mode:'mobile'};
draft = model.lineDraft(legacy,data);
assert.deepEqual(draft.params,{terminal_mode:'mobile',auth_server:'2.2.2.2'});
assert.deepEqual(legacy.params,{...model.endpoints('2.2.2.2'),terminal_mode:'mobile'});
legacy.params.status_url = 'https://special.example:443/status';
draft = model.lineDraft(legacy,data);
assert.equal(draft.params.status_url,legacy.params.status_url,'custom endpoint must survive server changes');
draft.params.auth_server = '3.3.3.3';
assert.equal(model.saveLine(config,draft,null).connections[0].params.status_url,legacy.params.status_url);

draft = model.newLine(config,data,'c3');
assert.equal(draft.interface,'wan3');
assert.equal(draft.enabled,false);
assert.equal(draft.auto_login,false);
draft.account = '__new__';
const inline = {id:'a2',label:'',credential_type:'username_password',values:{username:'fake-new-user',password:'fake-new-pass'}};
next = model.saveLine(config,draft,inline);
assert.equal(next.accounts.length,2);
assert.equal(next.connections[2].account,'a2');
assert.equal(next.accounts[1].label,'fake-new-user');
assert.equal(JSON.stringify(config),original,'inline account and line must be staged atomically');
assert.throws(()=>model.saveLine(config,draft,{...inline,values:{username:'x',password:''}}),/密码/);
assert.equal(JSON.stringify(config),original,'failed inline creation must not leave an account');
assert.equal(next.connections[0].account,next.connections[1].account,'shared account binding remains');

const edit = model.accountDraft(account);
edit.label = 'Renamed';
next = model.saveAccount(config,edit);
assert.equal('password' in next.accounts[0].values,false,'blank edit must preserve server-side password');
assert.deepEqual(next.connections,config.connections);
edit.values.password = 'fake-replacement';
assert.equal(model.saveAccount(config,edit).accounts[0].values.password,'fake-replacement');
new Function(fs.readFileSync('packages/luci-app-campuslink/htdocs/luci-static/resources/view/campuslink/main.js','utf8'));
console.log('PASS: old URLs/custom overrides, server change, isolated edits/cancel, atomic inline account, shared account and password retention');
